#!/usr/bin/env python3
"""extract_reference.py — turn the generated LaTeX tables into a flat CSV.

The paper's Tables 2–5 were generated by make_table.py / make_pluck_stats_table.py,
and an artifact run produces the same .tex files. This module parses either into
rows of

    table,program,metric,status,value

so compare_to_paper.py can join a run against the paper cell by cell.

  table   table2 (inference_standard.tex), table3 (inference_applied.tex),
          table4 (pluck_stats.tex), table5 (pluck_stats_full.tex), fig1 (fig1_metrics.tex)
  metric  a system (pluck, psi, hybit, slicstan, siren, turing), a speedup or
          error column, or a Hybrid Pluck statistic (bdd_nodes, ..., t_posterior)
  status  ok | t/o | o/m | n/i (not implemented) | n/r (not run) | r/e (rel. error > 5%) | error |
          inf (speedup with no competitor) | geq (value is a lower bound) | blank
  value   seconds, counts, ratios or fractions (errors as fractions, not percent)

Usage (regenerates experiments/reference/paper_reference.csv from the paper's .tex):
    python extract_reference.py [--tex-dir DIR] [--out CSV]
"""

from __future__ import annotations

import argparse
import csv
import os
import re

import bench_common as bc
import make_pluck_stats_table as st
import make_table as mt

TABLE_FILES = {
    "table2": "inference_standard.tex",
    "table3": "inference_applied.tex",
    "table4": "pluck_stats.tex",
    "table5": "pluck_stats_full.tex",
}
TABLE2_METRICS = ["speedup", "pluck", "psi", "hybit", "hybit_err"]
TABLE3_METRICS = ["speedup_exact", "speedup_approx", *mt.DISPLAY_SYSTEMS]
STATS_METRICS = ["bdd_nodes", "bdd_vars", "spn_interned", "spn_tree", "spn_compression",
                 "t_symbolic", "t_wmc", "t_posterior"]

_UNWRAP = [
    re.compile(r"^\{\\boldmath\\textbf\{(.*)\}\}$"),
    re.compile(r"^\{\\boldmath (.*)\}$"),
    re.compile(r"^\\underline\{(.*)\}$"),
    re.compile(r"^\\textcolor\{[^}]*\}\{(.*)\}$"),
]
_NUM = re.compile(r"^\$?\{?(?:\\geq\}?)?\$?([-\d.,]+)(?:\{\\times\}10\^\{(-?\d+)\})?\$?$")


def parse_cell(cell: str) -> tuple[str, float | None]:
    """(status, value) of one rendered table cell."""
    c = re.sub(r"\\cellcolor\{[^}]*\}", "", cell).strip()
    changed = True
    while changed:
        changed = False
        for rx in _UNWRAP:
            m = rx.match(c)
            if m:
                c, changed = m.group(1).strip(), True
    if c == "":
        return "blank", None
    if "t/o" in c:
        return "t/o", None
    if "n/r" in c:
        return "n/r", None
    if "o/m" in c:
        return "o/m", None
    if r"\_\_" in c:
        return "n/i", None
    if "r/e" in c:
        return "r/e", None
    if c == r"$\times$":
        return "error", None
    if c == "--":
        return "blank", None
    if c == r"$\infty$":
        return "inf", None
    if c == r"${\geq}2^{32}$":
        return "geq", float(2 ** 32)
    status = "geq" if r"\geq" in c else "ok"
    c = c.replace(r"$\geq$", "")
    if c.startswith("(") and c.endswith(")"):        # PSI unsimplified integral
        c = c[1:-1]
    scale = 1.0
    if c.endswith(r"\%"):                             # relative error in percent
        c, scale = c[:-2], 0.01
    c = c.replace(r"$^{\dagger}$", "")                # absolute error marker
    if c.endswith("x"):                               # speedup / compression factor
        c = c[:-1]
    m = _NUM.match(c)
    if not m:
        raise ValueError(f"unparsed cell: {cell!r}")
    value = float(m.group(1).replace(",", "")) * scale
    if m.group(2):
        value *= 10 ** int(m.group(2))
    return status, value


def _split_row(line: str) -> list[str]:
    """Split a tabular row on unescaped '&', dropping the trailing \\\\ (or \\\\*).
    A centred \\multicolumn{k}{c}{X} spanning k data columns becomes k copies of X."""
    body = re.sub(r"\\\\\*?\s*$", "", line.strip())
    cells = []
    for c in (c.strip() for c in re.split(r"(?<!\\)&", body)):
        m = re.match(r"^\\multicolumn\{(\d+)\}\{c\}\{(.*)\}$", c)
        cells += [m.group(2)] * int(m.group(1)) if m else [c]
    return cells


def table_rows(tex: str):
    """Yield (group, label_cell, data_cells) for every data row of a generated
    table; `group` is the enclosing \\multicolumn{..}{l}{\\textbf{Title}} header
    (None for a top-level row). Commented-out lines are skipped."""
    group = None
    for raw in tex.splitlines():
        line = raw.strip()
        if not line or line.startswith("%") or not re.search(r"\\\\\*?$", line):
            continue
        m = re.match(r"^\\multicolumn\{\d+\}\{l\}\{\\textbf\{(.*?)\}(?:~\\cite\w*\{[^}]*\})?\}\s*\\\\\*?$", line)
        if m:
            group = m.group(1)
            continue
        cells = _split_row(line)
        if len(cells) < 3 or "multicolumn{1}{l}" in line or "scriptsize" in line:
            continue                                   # header rows
        if cells[0].startswith(r"\quad"):
            yield group, cells[0], cells[1:]
        elif cells[0].startswith(r"\textbf{"):
            group = None
            yield None, cells[0], cells[1:]
        elif cells[0].startswith(r"\multirow") or (cells[0] == "" and r"\multicolumn" not in line):
            yield None, cells[1], cells[2:]            # table2: section column first


def _table2_programs() -> dict[str, str]:
    return {mt.latex_escape(disp): prog
            for _t, _f, rows in mt.TABLE1_SECTIONS for disp, prog in rows}


def _table3_programs() -> list[tuple[str | None, str]]:
    """(expected sub-row label or None, program) in make_table's row order."""
    fams = bc.families(bc.pluck_benchmarks())
    out = []
    for g in mt.TABLE2_GROUPS:
        if g["kind"] == "single":
            out.append((None, g["program"]))
        elif g["kind"] == "variants":
            out += [(lbl, prog) for lbl, prog in g["rows"]]
        else:
            out += [(lbl, prog) for lbl, prog in g.get("prefix_rows", [])]
            sizes = fams.get(g["family"], {"sizes": {}})["sizes"]
            out += [(g["label_fmt"].format(n=s), sizes[s]) for s in g["sizes"] if s in sizes]
    return out


def _stats_programs() -> dict[tuple[str | None, str], str]:
    """(group title, label cell) -> program for the Hybrid Pluck statistics tables."""
    progs = bc.pluck_benchmarks()
    fams = bc.families(progs)
    titles = st._prog_titles()
    out: dict[tuple[str | None, str], str] = {}
    for fam, info in fams.items():
        title = mt.latex_escape(st.family_title(fam))
        for lbl, prog in st.FAM_INFO.get(fam, {}).get("prefix_rows", []):
            out[(title, st._sub_label(lbl))] = prog
        for size, prog in info["sizes"].items():
            label = (st._sub_label(prog) if size is None
                     else st.variant_label(fam, info["letter"], size))
            out[(title, label)] = prog
    for title, rows in st.VARIANT_GROUPS:
        for lbl, prog in rows:
            out[(mt.latex_escape(title), st._sub_label(lbl))] = prog
    for prog in bc.standalone_programs(progs, fams):
        out[(None, r"\textbf{%s}" % mt.latex_escape(titles.get(prog, prog)))] = prog
    return out


def parse_table(table: str, tex: str) -> list[dict]:
    rows = list(table_rows(tex))
    out = []

    def emit(prog, metrics, cells):
        if len(cells) != len(metrics):
            raise ValueError(f"{table}/{prog}: {len(cells)} cells for {len(metrics)} metrics")
        for metric, cell in zip(metrics, cells):
            status, value = parse_cell(cell)
            out.append({"table": table, "program": prog, "metric": metric,
                        "status": status, "value": value})

    if table == "table2":
        names = _table2_programs()
        for _g, label, cells in rows:
            emit(names[label], TABLE2_METRICS, cells)
    elif table == "table3":
        expected = _table3_programs()
        if len(expected) != len(rows):
            raise ValueError(f"table3: {len(rows)} rows, generator order has {len(expected)}")
        for (lbl, prog), (_g, label, cells) in zip(expected, rows):
            if lbl is not None and label != r"\quad{\itshape %s}" % mt.latex_escape(lbl):
                raise ValueError(f"table3: row {label!r} does not match {prog} ({lbl!r})")
            emit(prog, TABLE3_METRICS, cells)
    else:
        names = _stats_programs()
        for group, label, cells in rows:
            key = (group, label)
            if key not in names:
                raise ValueError(f"{table}: unknown row {key!r}")
            emit(names[key], STATS_METRICS, cells)
    return out


def parse_fig1(tex: str) -> list[dict]:
    """fig1_metrics.tex macros -> rows (metric loc / time_s)."""
    out = []
    progs = {"Polyreg": "polyreg", "Sir": "sir", "Changepoint": "changepoint",
             "DawidSkene": "dawid_skene", "Mixture": "mixture"}
    for kind, name, val in re.findall(r"\\FigOne(LoC|Time)(\w+)\}\{([^}]*)\}", tex):
        prog = f"fig_{progs[name]}_listing"
        if kind == "LoC":
            out.append({"table": "fig1", "program": prog, "metric": "loc",
                        "status": "ok", "value": float(val)})
        else:
            m = re.match(r"([\d.]+)\\,(m?s)", val)
            secs = float(m.group(1)) * (1e-3 if m.group(2) == "ms" else 1.0)
            out.append({"table": "fig1", "program": prog, "metric": "time_s",
                        "status": "ok", "value": secs})
    return out


def extract(tex_dir: str) -> list[dict]:
    """Every parseable row from the .tex tables present in `tex_dir`."""
    rows = []
    for table, fname in TABLE_FILES.items():
        path = os.path.join(tex_dir, fname)
        if os.path.isfile(path):
            with open(path) as fh:
                rows += parse_table(table, fh.read())
    path = os.path.join(tex_dir, "fig1_metrics.tex")
    if os.path.isfile(path):
        with open(path) as fh:
            rows += parse_fig1(fh.read())
    return rows


def write_csv(rows: list[dict], path: str) -> None:
    with open(path, "w", newline="") as fh:
        w = csv.DictWriter(fh, fieldnames=["table", "program", "metric", "status", "value"])
        w.writeheader()
        for r in rows:
            w.writerow({**r, "value": "" if r["value"] is None else f"{r['value']:.6g}"})


def main():
    ref = os.path.join(bc.experiments_root(), "reference")
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--tex-dir", default=ref, help=f"dir holding the .tex tables (default: {ref})")
    ap.add_argument("--out", default=os.path.join(ref, "paper_reference.csv"))
    args = ap.parse_args()
    rows = extract(args.tex_dir)
    write_csv(rows, args.out)
    counts: dict[str, int] = {}
    for r in rows:
        counts[r["table"]] = counts.get(r["table"], 0) + 1
    print(f"wrote {args.out}: " + ", ".join(f"{t}={n}" for t, n in counts.items()))


if __name__ == "__main__":
    main()
